#[derive(Debug, buck2_error::Error)]
#[buck2(tag = Tier0)]
enum DaemonError {
    #[error("The buckd pid file at `{}` had a mismatched pid, expected `{1}`, got `{2}`", _0.display())]
    PidFileMismatch(PathBuf, u32, u32),
}

/// Start or run buck daemon.
///
/// This is an internal command, not intended to be used directly.
/// Buck client invokes it to spawn a server process.
#[derive(Clone, Debug, clap::Parser)]
pub struct DaemonCommand {
    /// Sets the interval for how often the daemon performs consistency checks.
    /// These are used to ensure that the daemon is still the one referenced
    /// by files in the daemon dir.
    #[clap(long, default_value("60"))]
    checker_interval_seconds: u64,
    /// Run buck daemon but do not daemonize the process.
    #[clap(long)]
    dont_daemonize: bool,
    /// This flag is set to prevent infinite recursion when the process is restarted
    /// with lower priority.
    #[clap(long)]
    skip_macos_qos: bool,
    /// Early configs that the daemon needs at startup. Those are read by the client then passed to
    /// the daemon. The client restarts it when startup options or daemon settings mismatch.
    #[clap(value_parser = buck_error_clap_parser(DaemonStartupConfig::deserialize))]
    daemon_startup_config: DaemonStartupConfig,

    #[clap(env("ENABLE_TRACE_IO"), long)]
    enable_trace_io: bool,

    /// If passed a given materializer identity, if the materializer state DB matches that
    /// identity, the daemon will not use it and will instead create a new empty materializer
    /// state.
    #[clap(long)]
    reject_materializer_state: Option<String>,

    /// If set, indicates that this daemon is running in dedicated cgroup.
    #[clap(long)]
    has_cgroup: bool,

    /// The cgroup path of the process that launched this daemon before Buck moved the daemon into
    /// its managed cgroup.
    #[clap(long)]
    daemon_originating_cgroup: Option<String>,

    /// The daemon id that has been assigned to this daemon.
    ///
    /// Generated by the client.
    #[clap(long)]
    daemon_id: String,

    #[clap(long, hide = true)]
    started_for_clean_stale: bool,
}

impl DaemonCommand {
    /// Command instance for `--no-buckd`.
    pub(crate) fn new_in_process(daemon_startup_config: DaemonStartupConfig) -> DaemonCommand {
        DaemonCommand {
            checker_interval_seconds: 60,
            dont_daemonize: true,
            skip_macos_qos: true,
            daemon_startup_config,
            enable_trace_io: false,
            reject_materializer_state: None,
            has_cgroup: false,
            daemon_originating_cgroup: None,
            daemon_id: DaemonId::new().to_string(),
            started_for_clean_stale: false,
        }
    }
}

pub(crate) fn init_listener() -> buck2_error::Result<(std::net::TcpListener, ConnectionType)> {
    let (endpoint, listener) = create_listener()?;

    tracing::info!("Listener created on {}", &endpoint);

    Ok((listener, endpoint))
}

pub(crate) fn write_process_info(
    daemon_dir: &DaemonDir,
    process_info: &DaemonProcessInfo,
) -> buck2_error::Result<()> {
    let file = File::create(daemon_dir.buckd_info())?;
    serde_json::to_writer(&file, &process_info)?;
    // Fsync so the endpoint/auth token are durable before clients race
    // to read this file; a crash here would otherwise lose them.
    file.sync_all()?;
    Ok(())
}

fn verify_current_daemon(daemon_dir: &DaemonDir) -> buck2_error::Result<()> {
    let file = daemon_dir.buckd_pid();
    let my_pid = process::id();

    let recorded_pid: u32 = fs_util::read_to_string(&file)
        .categorize_internal()?
        .trim()
        .parse()?;
    if recorded_pid != my_pid {
        return Err(
            DaemonError::PidFileMismatch(file.into_path_buf(), my_pid, recorded_pid).into(),
        );
    }

    Ok(())
}

/// This daemon's start time for `buckd.info`, or 0 when it cannot be read.
/// Readers treat 0 as "unknown" and fall back to pid-only identity, so a
/// failed read is reported rather than silently producing an unverifiable file.
fn recorded_start_time() -> u64 {
    match process_start_time(None) {
        Some(start_time) => start_time,
        None => {
            soft_error_or_panic!(
                "daemon_pid_start_time_unavailable",
                buck2_error!(
                    ErrorTag::DaemonStartupFailed,
                    "Could not read this daemon's process start time; recording 0 in buckd.info"
                ),
                task: false,
            );
            0
        }
    }
}

fn gen_auth_token() -> String {
    (0..20).map(|_| rand::random_range('a'..='z')).collect()
}

fn terminate_on_panic() {
    let orig_hook = std::panic::take_hook();
    std::panic::set_hook(Box::new(move |panic_info| {
        orig_hook(panic_info);
        // Flush PGO profile data before _exit, which skips atexit handlers.
        buck2_util::pgo::flush_pgo_profile();
        // We are using `_exit` instead of `exit` to avoid running global destructors.
        // This is similar to what default rust panic handler does
        // when there `panic=abort`: it does `abort`.
        unsafe { libc::_exit(1) }
    }));
}

fn verify_buck_out_dir(paths: &InvocationPaths) -> buck2_error::Result<()> {
    let path = paths.buck_out_path();

    fs_util::create_dir_all(path.clone()).map_err(|e| {
        e.tag([ErrorTag::InvalidBuckOut]).context(format!(
            "Failed to create buck-out directory `{}`. \
             The path or a parent directory may be on a stale mount, \
             be a broken symlink, a file, or the project root may no longer be \
             accessible. \
             Try running `buck2 kill` and re-run your command.",
            path,
        ))
    })?;

    const CACHEDIR_TAG_CONTENTS: &str = r#"Signature: 8a477f597d28d172789f06886806bc55
# This file is a cache directory tag created by Buck2.
# For information about cache directory tags, see:
#    http://www.brynosaurus.com/cachedir/
"#;

    if let Some(mut file) =
        fs_util::create_file_if_not_exists(path.join(ForwardRelativePath::new("CACHEDIR.TAG")?))?
    {
        file.write_all(CACHEDIR_TAG_CONTENTS.as_bytes())?;
    }

    Ok(())
}

impl DaemonCommand {
    fn run(
        self,
        log_reload_handle: Arc<dyn LogConfigurationReloadHandle>,
        paths: InvocationPaths,
        in_process: bool,
        ready: Box<dyn FnOnce() + Send>,
    ) -> buck2_error::Result<()> {
        let prepped_cgroups = if self.has_cgroup {
            // Note: It's important that we do this before daemonizing, as otherwise there may be
            // stray processes laying around in this cgroup
            Some(PreppedBuckCgroups::prep_current_process()?)
        } else {
            None
        };
        // NOTE: Do not create any threads before this point.
        //   Daemonize does not preserve threads.

        daemon_lower_priority(
            self.skip_macos_qos,
            self.daemon_startup_config.startup_options.macos_qos_class,
        )?;

        // TODO(nga): this breaks relative paths in `--no-buckd`.
        //   `--no-buckd` should capture correct directories earlier.
        //   Or even better, client should set current directory to project root,
        //   and resolve all paths relative to original cwd.
        fs_util::set_current_dir(paths.project_root().root()).categorize_internal()?;

        let server_init_ctx = BuckdServerInitPreferences {
            enable_trace_io: self.enable_trace_io,
            reject_materializer_state: self.reject_materializer_state.map(|s| s.into()),
            daemon_startup_config: self.daemon_startup_config,
            daemon_originating_cgroup: self.daemon_originating_cgroup,
            started_for_clean_stale: self.started_for_clean_stale,
            in_process,
        };

        let span = tracing::info_span!("daemon_listener");
        let span_guard = span.enter();

        if buck2_env!(
            "BUCK2_TEST_DAEMON_STARTUP_SIGNAL",
            bool,
            applicability = testing
        )? {
            #[cfg(unix)]
            unsafe {
                libc::raise(libc::SIGTERM);
            }
        }

        let daemon_dir = paths.daemon_dir()?;
        let pid_path = daemon_dir.buckd_pid();
        let stdout_path = daemon_dir.buckd_stdout();
        let stderr_path = daemon_dir.buckd_stderr();
        // Even if we don't redirect output, we still need to create stdout/stderr files,
        // because tailer opens them. This is untidy.
        let stdout = File::create(stdout_path)?;
        let stderr = File::create(stderr_path)?;

        let auth_token = gen_auth_token();

        let (listener, process_info, endpoint) = if !self.dont_daemonize {
            // We must create stdout/stderr before creating a listener,
            // otherwise it is race:
            // * daemon parent process exits
            // * client successfully connects to the unix socket
            // * but stdout/stderr may be not yet created, so tailer fails to open them
            let (listener, endpoint) = init_listener()?;

            Self::daemonize(stdout, stderr)?;
            Self::exit_bpfjailer();

            fs_util::write(&pid_path, format!("{}", process::id())).categorize_internal()?;

            let pid = process::id();
            let process_info = DaemonProcessInfo {
                pid: pid as i64,
                endpoint: endpoint.to_string(),
                version: BuckVersion::get()?.unique_id().to_owned(),
                auth_token,
                pid_start_time: recorded_start_time(),
            };

            // TODO(nga): this code is executed after server daemonization,
            //   so client has to retry to read it. Fix it.
            write_process_info(&daemon_dir, &process_info)?;

            tracing::info!("Daemonized.");

            (listener, process_info, endpoint)
        } else {
            fs_util::write(&pid_path, format!("{}", process::id())).categorize_internal()?;

            if !in_process {
                Self::redirect_output(stdout, stderr)?;
            }

            let (listener, endpoint) = init_listener()?;

            let process_info = DaemonProcessInfo {
                pid: process::id() as i64,
                endpoint: endpoint.to_string(),
                version: BuckVersion::get()?.unique_id().to_owned(),
                auth_token,
                pid_start_time: recorded_start_time(),
            };

            write_process_info(&daemon_dir, &process_info)?;

            (listener, process_info, endpoint)
        };

        // Start the fragmentation dump watcher now that we are in the final
        // (post-daemonize-fork) process; threads do not survive that fork.
        #[cfg(buck2_memfrag)]
        mem_frag::start_dump_watcher();

        let daemon_id = DaemonId::parse_from_str(&self.daemon_id)?;
        set_daemon_id_for_panics(daemon_id.dupe());

        tracing::info!("Starting Buck2 daemon");
        tracing::info!("Version: {}", BuckVersion::get_version()?);
        tracing::info!("PID: {}", process::id());
        tracing::info!("ID: {}", daemon_id);
        tracing::info!("Endpoint: {}", endpoint);

        terminate_on_panic();

        maybe_schedule_termination()?;

        // Raise file descriptor limits. The default on modern macOS is
        // pathetically low (256!!!), and distros like Fedora Asahi have a limit
        // as low as 1024, which can easily be exceeded on any modern machine.
        buck2_common::rlimits::raise_file_descriptor_limits()?;

        // Higher performance for jemalloc, recommended (but may not have any effect on Mac)
        // https://github.com/jemalloc/jemalloc/blob/dev/TUNING.md#notable-runtime-options-for-performance-tuning
        memory::enable_background_threads()?;

        // Lets DICE attribute the memory paging actually moves, by reading the
        // allocator's per-thread counters around the work that frees and rebuilds
        // values. Without a reader installed the totals stay zero.
        //
        // Not on Windows: `mem_frag` reaches jemalloc through bare
        // `__attribute__((weak))` symbols, which need linker support it only has
        // on ELF and Mach-O. Linking it into a Windows build makes the binary
        // fault on startup, so the BUCK dep is gated to match this `cfg`.
        //
        // The runtime check is still needed where jemalloc is simply not the
        // allocator, such as `mode/dev`. It is the precondition itself rather
        // than a proxy for one: folly establishes it by reading
        // `thread.allocatedp`, the very counter the reader goes on to use.
        #[cfg(all(fbcode_build, not(windows)))]
        if memory::is_using_jemalloc() {
            dice::set_thread_alloc_counters(mem_frag::thread_alloc_counters);
        }

        let fb = buck2_common::fbinit::get_or_init_fbcode_globals();

        if cfg!(target_os = "linux") {
            #[cfg(fbcode_build)]
            {
                gflags::set_gflag_value(
                    fb,
                    "cgroup2_reader_update_interval_ms",
                    gflags::GflagValue::U32(2000),
                )
                .expect("failed to set gflag --cgroup2_reader_update_interval_ms");
            }
        }

        // Unfortunately, buck-out doesn't really have a well-defined place/time at which it creates
        // the buck-out dir, instead just creating it whenever it first wants to write something to
        // it. We don't want to create it unconditionally on all commands as there are lots of
        // client commands (help, log, etc.) that should not require a buck-out just to be able to
        // run. However, at the point at which we're starting a daemon it does seem sensible to now
        // ensure that it always exists, primarily so that we can put a file into it to mark it as a
        // cachedir.
        verify_buck_out_dir(&paths)?;

        let mut builder = new_tokio_runtime("buck2-rt");
        builder.enable_all();

        if let Some(num_tokio_workers) = server_init_ctx
            .daemon_startup_config
            .startup_options
            .num_tokio_workers
            .or(buck2_env!("BUCK2_RUNTIME_THREADS", type=usize)?)
        {
            if num_tokio_workers > 0 {
                builder.worker_threads(num_tokio_workers);
            }
        }

        if let Some(threads) = buck2_env!("BUCK2_MAX_BLOCKING_THREADS", type=usize)? {
            builder.max_blocking_threads(threads);
        }

        // Enable the per-worker poll-time histogram, used for tokio telemetry.
        //
        // Tokio documents the cost of this as being 2 `Instant::new` calls per poll. Telemetry from
        // real builds shows that we cap out at ~10k polls/sec/worker. With `Instant::new` being
        // ~50ns, that puts the cost of these polls at 0.1% CPU, which is an acceptable cost to pay
        // for the value of the telemetry.
        //
        // The histogram config is sized for `buck2_webconsole`'s display bands, which bin polls at
        // decade boundaries between 1µs and 1s. `precision_exact(0)` gives one bucket per power of
        // 2 (≈3 buckets per decade — finer than the bands but coarse enough to not blow up event
        // log size); `min_value` and `max_value` pin the bucket range so we don't carry hundreds
        // of empty buckets covering the sub-ns and >1-minute extremes that tokio's default range
        // would include. End result: ~24 buckets per worker per snapshot instead of the default
        // ~237 — a ~10x reduction in histogram payload.
        builder.enable_metrics_poll_time_histogram();
        builder.metrics_poll_time_histogram_configuration(
            tokio::runtime::HistogramConfiguration::log(
                tokio::runtime::LogHistogram::builder()
                    .min_value(std::time::Duration::from_nanos(500))
                    .max_value(std::time::Duration::from_secs(1))
                    .precision_exact(0)
                    .build(),
            ),
        );

        tracing::info!("Starting tokio runtime...");

        let worker_runtime = builder
            .build()
            .buck_error_context("Error creating Tokio runtime")?;
        let handle = worker_runtime.handle().clone();

        let tonic_runtime = new_tokio_runtime("buck2-tn")
            .enable_all()
            // These values are arbitrary, but I/O shouldn't take up many threads.
            .worker_threads(2)
            .max_blocking_threads(2)
            .build()
            .buck_error_context("Error creating Tonic Tokio runtime")?;

        let result = tonic_runtime.block_on(async move {
            // Once any item is received on the hard_shutdown_receiver, the daemon process will exit immediately.
            let (hard_shutdown_sender, mut hard_shutdown_receiver) = mpsc::unbounded();

            let daemon_dir = paths.daemon_dir()?;
            let project_root = paths.project_root().root().as_path().to_path_buf();

            listener.set_nonblocking(true)?;
            let listener = tokio::net::TcpListener::from_std(listener)?;
            let listener = tokio_stream::wrappers::TcpListenerStream::new(listener);

            // Patch socket options to include TCP_NODELAY for a material performance improvement
            let listener = listener.map(|stream| {
                stream.inspect(|stream| {
                    match stream.set_nodelay(true) {
                        Ok(()) => {}
                        Err(e) => {
                            // Failing to set nodelay causes a performance penalty
                            // but is still better than failing to set up the connection
                            tracing::info!("Failed to set nodelay TCP option: {}", e);
                        }
                    }
                })
            });

            tracing::info!("Listening.");
            // `tracing::info` statements after this is dropped are not logged by default due to `[daemon_listener]=info` filter.
            drop(span_guard);

            let daemon_constraints =
                gen_daemon_constraints(&server_init_ctx.daemon_startup_config, &daemon_id)?;

            let buckd_server = BuckdServer::run(
                fb,
                log_reload_handle,
                paths,
                server_init_ctx,
                process_info,
                prepped_cgroups,
                daemon_constraints,
                Box::pin(listener),
                handle,
                daemon_id,
                ready,
            )
            .fuse();
            let shutdown_future = async move { hard_shutdown_receiver.next().await }.fuse();
            pin_mut!(buckd_server);
            pin_mut!(shutdown_future);

            let checker_interval_seconds = self.checker_interval_seconds;

            thread_spawn("check-daemon-dirs", move || {
                Self::check_daemon_dirs_thread(
                    checker_interval_seconds,
                    daemon_dir,
                    project_root,
                    hard_shutdown_sender,
                )
            })?;

            select! {
                res = buckd_server => {
                    res
                }
                reason = shutdown_future => {
                    let reason = reason.as_deref().unwrap_or("no reason available");
                    eprintln!("server forced shutdown: {}", reason);
                    Ok(())
                },
            }
        });

        if !in_process {
            // Shutting down a Tokio runtime immediately cancels all of the tasks; cancelling the
            // tasks at the tokio level ends up breaking invariants that we expect around
            // `CancellableFuture` from `dice_futures` being the only thing that causes cancellation
            // which is pretty hard to deal with correctly. Forget the runtime so that things aren't
            // cancelled. We're about to `libc::_exit` anyway so no real harm.
            std::mem::forget(worker_runtime);
        }

        result
    }

    /// We start a dedicated thread to periodically check that the files in the daemon
    /// dir still reflect that we are the current buckd and verify that when you connect
    /// to the server it is our server. Also checks that the project root is still
    /// accessible.
    /// It gets a dedicated thread so that if somehow the main runtime gets all jammed up,
    /// this will still run (and presumably connecting to the server or our request would
    /// then fail and we'd do a hard shutdown).
    fn check_daemon_dirs_thread(
        checker_interval_seconds: u64,
        daemon_dir: DaemonDir,
        project_root: PathBuf,
        hard_shutdown_sender: UnboundedSender<String>,
    ) {
        let checker_interval_seconds = buck2_env!(
            "BUCK2_TESTING_CHECKER_INTERVAL_SECONDS",
            type = u64,
            applicability = testing
        )
        .ok()
        .flatten()
        .unwrap_or(checker_interval_seconds);

        loop {
            std::thread::sleep(Duration::from_secs(checker_interval_seconds));
            match verify_current_daemon(&daemon_dir) {
                Ok(()) => {}
                Err(e) => {
                    // This bit of code cannot relay errors, ignoring that we can't log
                    // a warning is reasonable.
                    let _ignored = buck2_client_ctx::eprintln!(
                        "daemon verification failed, forcing shutdown: {:#}",
                        e
                    );

                    // If this is already shutting down, we don't need to do it again.
                    let _ignored = hard_shutdown_sender
                        .unbounded_send("Daemon verification failed".to_owned());
                }
            };

            // Check if the project root has gone stale. This is increasingly
            // important as people use more temporary checkouts.
            let dir_check = std::fs::metadata(&project_root);
            if let Err(e) = dir_check {
                let msg = format!(
                    "Project root {} is no longer accessible: {:#}",
                    project_root.display(),
                    e
                );
                let _ignored = buck2_client_ctx::eprintln!("{}", msg);

                soft_error_or_panic!(
                    "daemon_project_root_unavailable",
                    buck2_error!(
                        ErrorTag::MissingProjectRoot,
                        "Project root `{}` is no longer accessible: {:#}",
                        project_root.display(),
                        e
                    ),
                    task: false,
                );

                let _ignored = hard_shutdown_sender.unbounded_send(msg);
            }
        }
    }

    pub fn exec(
        self,
        log_reload_handle: Arc<dyn LogConfigurationReloadHandle>,
        paths: InvocationPaths,
        in_process: bool,
        ready: Box<dyn FnOnce() + Send>,
    ) -> buck2_error::Result<()> {
        let daemon_dir = paths.daemon_dir()?;
        if !daemon_dir.path.is_dir() {
            fs_util::create_dir_all(&daemon_dir.path)?;
        }

        let res = self.run(log_reload_handle, paths, in_process, ready);
        if let Err(err) = res.as_ref() {
            fs_util::write(
                daemon_dir.buckd_error_log(),
                serde_json::to_string(&buck2_data::ErrorReport::from(err))?,
            )
            .categorize_internal()?;
        }
        // Flush PGO profile data on all daemon exit paths (graceful kill,
        // dir mismatch, inactivity timeout, errors).
        buck2_util::pgo::flush_pgo_profile();
        res
    }

    #[cfg(unix)]
    fn redirect_output(stdout: File, stderr: File) -> buck2_error::Result<()> {
        nix::unistd::dup2_stdout(&stdout)?;
        nix::unistd::dup2_stderr(&stderr)?;
        Ok(())
    }

    #[cfg(windows)]
    fn redirect_output(stdout: File, stderr: File) -> buck2_error::Result<()> {
        use std::os::windows::io::AsRawHandle;

        unsafe {
            let stdout_fd = libc::open_osfhandle(stdout.as_raw_handle() as isize, libc::O_RDWR);
            let stderr_fd = libc::open_osfhandle(stderr.as_raw_handle() as isize, libc::O_RDWR);
            if stdout_fd == -1 || stderr_fd == -1 {
                return Err(buck2_error!(
                    ErrorTag::DaemonRedirect,
                    "Can't get file descriptors for output files",
                ));
            }
            // MSVC libc doesn't export STDOUT_FILENO and STDERR_FILENO.
            let stdout_exit_code = libc::dup2(stdout_fd, 1);
            let stderr_exit_code = libc::dup2(stderr_fd, 2);
            if stdout_exit_code == -1 || stderr_exit_code == -1 {
                return Err(buck2_error!(
                    ErrorTag::DaemonRedirect,
                    "Failed to redirect daemon output"
                ));
            }
        }
        Ok(())
    }

    #[cfg(unix)]
    fn daemonize(stdout: File, stderr: File) -> buck2_error::Result<()> {
        // TODO(cjhopman): Daemonize is pretty un-maintained. We may need to move
        // to something else or just do it ourselves.
        let daemonize = crate::daemonize::Daemonize::new()
            .stdout(stdout)
            .stderr(stderr);
        daemonize.start()?;
        Ok(())
    }

    #[cfg(windows)]
    /// Restart current process in detached mode with '--dont-daemonize' flag.
    fn daemonize(_stdout: File, _stderr: File) -> buck2_error::Result<()> {
        Err(buck2_error!(
            ErrorTag::WindowsUnsupported,
            "Cannot daemonize on Windows"
        ))
    }

    #[cfg(all(fbcode_build, target_os = "linux"))]
    fn exit_bpfjailer() {
        // Attempts to request that the BPFJailer remove this process (pid=0)
        // from all jail Role IDs (uuid=""). If the process was not in any jail
        // to begin with, this is a no-op.
        //
        // Note that there IS a `buck` Role ID that is assigned to us based on
        // our cgroup name, and it's this role that allows the exit_jail request
        // here to succeed.
        let Some(sock_path) = BPFJAILER_SOCK_PATHS
            .iter()
            .find(|sock_path| std::path::Path::new(sock_path).exists())
        else {
            return;
        };

        match bpfjailer_handler_polyglot::exit_jail(
            sock_path.to_string(),
            "".to_owned(),
            0,
            -1,
            BPFJAILER_CONNECT_TO_SOCKET_RETRY_MS,
            BPFJAILER_RESPONSE_FROM_SOCKET_TIMEOUT_MS,
        ) {
            Ok(()) => tracing::info!("Exited BPFJailer jail"),
            Err(e) => {
                soft_error_or_panic!(
                    "failed_to_exit_bpfjailer",
                    buck2_error::internal_error!("Failed to exit BPFJailer jail: {}", e)
                );
            }
        }
    }

    #[cfg(not(all(fbcode_build, target_os = "linux")))]
    fn exit_bpfjailer() {}
}

