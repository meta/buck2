class Raw(str):
    """A Starlark expression, written as is."""


def starlark(v, indent: int = 4) -> str:
    if isinstance(v, Raw):
        return str(v)
    if isinstance(v, bool):
        return "True" if v else "False"
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        if not v:
            return "[]"
        pad = " " * (indent + 4)
        items = "".join(f"{pad}{starlark(x, indent + 4)},\n" for x in v)
        return "[\n" + items + " " * indent + "]"
    raise TypeError(v)


def call(rule: str, **kwargs) -> str:
    body = "".join(
        f"    {k} = {starlark(v)},\n" for k, v in kwargs.items() if v is not None
    )
    return f"{rule}(\n{body})\n"


def write_generated(path: Path, text: str) -> None:
    if path.exists() and not path.read_text().startswith(HEADER):
        sys.exit(f"{path} exists and gen_buck.py did not write it")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEADER + text)


def maven_path(coord: str) -> str:
    g, a, v = coord.split(":")
    return f"{g.replace('.', '/')}/{a}/{v}/{a}-{v}.jar"


def module_label(prefix: str, info: dict) -> str:
    return f"//{prefix}{info['dir']}:{info['dir'].rsplit('/', 1)[-1]}"


def third_party_label(coord: str) -> str:
    ga = ":".join(coord.split(":")[:2])
    if ga in COORD_TARGETS:
        return f"//third-party:{COORD_TARGETS[ga]}"
    name = coord.split(":")[1]
    if name not in ARTIFACTS:
        sys.exit(f"model.json names a jar that gen_buck.py does not know: {coord}")
    return f"//third-party:{name}"


def compile_classpath(path: str, modules: dict) -> set:
    """The modules on a module's Gradle compile classpath: its project dependencies and,
    transitively, their `api` dependencies."""

    def add_api(d: str, out: set) -> None:
        for conf, x in modules[d]["deps"]:
            if conf == "api" and x not in out:
                out.add(x)
                add_api(x, out)

    out = set()
    for _conf, d in modules[path]["deps"]:
        out.add(d)
        add_api(d, out)
    out.discard(path)
    return out


def external_classpath(path: str, modules: dict) -> set:
    """group:artifact of the jars on a module's Gradle compile classpath."""
    out = {":".join(c.split(":")[:2]) for _conf, c in modules[path]["external"]}
    for d in compile_classpath(path, modules):
        out |= {
            ":".join(c.split(":")[:2])
            for conf, c in modules[d]["external"]
            if conf == "api"
        }
    return out


def source_roots(mdir: Path) -> list:
    """Gradle's projectDefault(): src/ (src/main/kotlin and src/main/java in Maven-layout
    modules) and gen/."""
    roots = []
    if (mdir / "src/main").is_dir():
        roots += [
            r for r in ("src/main/kotlin", "src/main/java") if (mdir / r).is_dir()
        ]
    elif (mdir / "src").is_dir():
        roots.append("src")
    if (mdir / "gen").is_dir():
        roots.append("gen")
    return roots


# Class ABI members in declaration order, as in the class jars that Gradle compiles against.
JVM_ABI_GEN_PRESERVE_DECLARATION_ORDER = (
    "plugin:org.jetbrains.kotlin.jvm.abi:preserveDeclarationOrder=true"
)


def kotlinc_args(info: dict) -> list:
    o = info["options"]
    args = list(GRADLE_COMPAT_ARGS if o["gradleCompat"] else COMMON_ARGS)
    args.append(f"-language-version={o['languageVersion']}")
    args.append(f"-api-version={o['apiVersion']}")
    args.append(f"-jvm-default={o['jvmDefault']}")
    args += [f"-opt-in={x}" for x in o["optIns"]]
    args += o["free"]
    args += ["-module-name", info["moduleName"]]
    args += ["-P", JVM_ABI_GEN_PRESERVE_DECLARATION_ORDER]
    return args


def gen_module(
    path: str, kotlin_src: Path, prefix: str, abi: str, modules: dict
) -> str:
    info = modules[path]
    mdir = kotlin_src / info["dir"]
    roots = source_roots(mdir)
    if not any(
        f.suffix in (".kt", ".java") for r in roots for f in (mdir / r).rglob("*")
    ):
        sys.exit(
            f"no sources for {path} in {mdir}: is --kotlin-src a v{KOTLIN_VERSION} checkout?"
        )
    has_kotlin = any(True for r in roots for _ in (mdir / r).rglob("*.kt"))
    # Gradle api -> exported_deps, implementation -> deps, compileOnly -> provided_deps.
    attr = {"api": [], "implementation": [], "compileOnly": []}
    for conf, d in info["deps"]:
        attr[conf].append(module_label(prefix, modules[d]))
    for conf, coord in info["external"]:
        attr[conf].append(third_party_label(coord))
    # kotlin-stdlib brings annotations 13.0, which Gradle replaces with coroutines' 23.0.0.
    if COROUTINES not in external_classpath(path, modules):
        attr["implementation"].append("//third-party:annotations")
    if path == ":compiler:util":  # resources.srcDir(File(rootDir, "resources"))
        attr["implementation"].append(f"//{prefix}resources:resources")
    out = ""
    resources = {}
    res_root = (
        "src/main/resources" if (mdir / "src/main/resources").is_dir() else "resources"
    )
    if path == ":compiler:compiler.version":
        # processResources replaces @snapshot@ with the compiler version.
        out += call(
            "genrule",
            name="compiler-version-resource",
            srcs=["resources/META-INF/compiler.version"],
            out="META-INF/compiler.version",
            cmd=f"sed 's/@snapshot@/{KOTLIN_VERSION}/' $SRCS > $OUT",
        )
        out += "\n" + call(
            "java_library",
            name="compiler-version-resources",
            resources=[":compiler-version-resource"],
            resources_root=".",
        )
        out += "\n"
        attr["api"].append(":compiler-version-resources")
    elif (mdir / res_root).is_dir():
        resources = {
            "resources": Raw(f'glob(["{res_root}/**"])'),
            "resources_root": res_root,
        }
    srcs = [f"{r}/**/*.{ext}" for ext in ("kt", "java") for r in roots]
    body = {
        "name": info["dir"].rsplit("/", 1)[-1],
        "srcs": Raw(f"glob({starlark(srcs)})"),
        **resources,
    }
    rule = "java_library"
    if has_kotlin:
        rule = "kotlin_library"
        source_only = (
            abi == "kosabi"
            and info["kosabiMode"] in ("flat", "chained")
            and path not in KOSABI_CLASS_MODULES
        )
        body["abi_generation_mode"] = "source_only" if source_only else "class"
        body["extra_kotlinc_arguments"] = kotlinc_args(info)
        if source_only and info["kosabiMode"] == "chained":
            # Kosabi reads the ABIs of these modules; without them it reads only the jars.
            body["source_only_abi_deps"] = sorted(
                module_label(prefix, modules[d])
                for d in compile_classpath(path, modules)
            )
    body.update(
        source="8",
        target="8",
        extra_arguments=JAVAC_ARGS,
        deps=sorted(set(attr["implementation"])),
        exported_deps=sorted(set(attr["api"])),
        provided_deps=sorted(set(attr["compileOnly"])),
        visibility=["PUBLIC"],
    )
    return out + call(rule, **body)


def gen_third_party(pins: dict) -> str:
    out = [
        "# Jars outside Maven Central can come from elsewhere with",
        "# `-c kotlin_compiler.<name>_url=<url> -c kotlin_compiler.<name>_sha256=<sha256>`.",
        "",
    ]
    for name, (repo, coord, exported) in sorted(ARTIFACTS.items()):
        _g, a, v = coord.split(":")
        hashes = pins[coord]
        if repo == CENTRAL:
            url = f"mvn:{coord.replace(f':{v}', f':jar:{v}')}"
            sha1, sha256 = hashes["sha1"], None
        else:
            default_url = f"{repo}/{maven_path(coord)}"
            url = Raw(f'read_config("kotlin_compiler", "{name}_url", "{default_url}")')
            sha1 = None
            sha256 = Raw(
                f'read_config("kotlin_compiler", "{name}_sha256", "{hashes["sha256"]}")'
            )
        out.append(
            call(
                "remote_file",
                name=f"{name}.jar",
                url=url,
                sha1=sha1,
                sha256=sha256,
                out=f"{a}-{v}.jar",
            )
        )
        out.append(
            call(
                "prebuilt_jar",
                name=name,
                binary_jar=f":{name}.jar",
                deps=[f":{d}" for d in exported] or None,
                visibility=["PUBLIC"],
            )
        )
    out.append(
        call(
            "java_library",
            name="intellij-core",
            exported_deps=[f":{x}" for x in INTELLIJ_CORE],
            visibility=["PUBLIC"],
        )
    )
    out.append("# javac internals (com.sun.tools.*) for the modules that wrap javac.")
    out.append(
        call(
            "http_archive",
            name="jdk8",
            urls=[JDK8_URL],
            sha256=JDK8_SHA256,
            strip_prefix=JDK8_PREFIX,
            sub_targets=["lib/tools.jar"],
        )
    )
    out.append(
        call(
            "prebuilt_jar",
            name="tools-jar-api",
            binary_jar=":jdk8[lib/tools.jar]",
            visibility=["PUBLIC"],
        )
    )
    return "\n".join(out)


