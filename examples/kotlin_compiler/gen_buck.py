def generate(project_root: Path, kotlin_src: Path, abi: str) -> None:
    project_root = project_root.resolve()
    kotlin_src = kotlin_src.resolve()
    if not kotlin_src.is_relative_to(project_root):
        sys.exit(
            f"--kotlin-src {kotlin_src} must be inside --project-root {project_root}"
        )
    prefix = str(kotlin_src.relative_to(project_root))
    prefix = "" if prefix == "." else prefix + "/"
    modules = json.loads((HERE / "model.json").read_text())["modules"]
    pins = json.loads((HERE / "pins.json").read_text())
    for path, info in modules.items():
        write_generated(
            kotlin_src / info["dir"] / "BUCK",
            gen_module(path, kotlin_src, prefix, abi, modules),
        )
    write_generated(
        kotlin_src / "resources/BUCK",
        call(
            "java_library",
            name="resources",
            resources=Raw('glob(["**"], exclude = ["BUCK"])'),
            resources_root=".",
            visibility=["PUBLIC"],
        ),
    )
    write_generated(project_root / "third-party/BUCK", gen_third_party(pins))
    write_generated(project_root / "toolchains/BUCK", TOOLCHAINS_BUCK)
    labels = sorted(module_label(prefix, i) for i in modules.values())
    root = call(
        "alias",
        name="cli-jvm",
        actual=module_label(prefix, modules[TARGET]),
        visibility=["PUBLIC"],
    )
    root += "\n" + call(
        "java_binary",
        name="kotlinc",
        main_class="org.jetbrains.kotlin.cli.jvm.K2JVMCompiler",
        deps=labels + [f"//third-party:{x}" for x in RUNTIME_EXTRA],
        visibility=["PUBLIC"],
    )
    write_generated(project_root / "BUCK", root)
    write_generated(
        project_root / ".buckconfig",
        BUCKCONFIG.format(prefix=prefix, kotlin_version=KOTLIN_VERSION),
    )
    print(f"{len(modules)} modules ({abi} ABIs) -> {project_root}")


def verification_sha256(kotlin_src: Path) -> dict:
    """sha256 of the jars that JetBrains' build pins in gradle/verification-metadata.xml."""
    text = (kotlin_src / "gradle/verification-metadata.xml").read_text()
    out = {}
    components = re.findall(
        r'<component group="([^"]+)" name="([^"]+)" version="([^"]+)">(.*?)</component>',
        text,
        re.S,
    )
    for g, a, v, body in components:
        m = re.search(
            rf'<artifact name="{re.escape(a)}-{re.escape(v)}\.jar">\s*<sha256 value="([0-9a-f]{{64}})"',
            body,
        )
        if m:
            out[f"{g}:{a}:{v}"] = m.group(1)
    return out


def pin(kotlin_src: Path) -> None:
    pins_path = HERE / "pins.json"
    old = json.loads(pins_path.read_text()) if pins_path.exists() else {}
    jetbrains = verification_sha256(kotlin_src)
    pins = {}
    for _name, (repo, coord, _exported) in sorted(ARTIFACTS.items()):
        url = f"{repo}/{maven_path(coord)}"
        try:
            with urllib.request.urlopen(url, timeout=300) as response:
                data = response.read()
        except OSError as e:
            if coord in old:
                print(f"kept the old pin of {coord}: {url}: {e}", file=sys.stderr)
                pins[coord] = old[coord]
                continue
            sys.exit(f"{url}: {e}")
        entry = {
            # Maven Central jars are pinned by sha1, like the prelude's own third-party jars.
            # patternlint-disable-next-line poor-choice-of-hash-function
            "sha1": hashlib.sha1(data).hexdigest(),
            "sha256": hashlib.sha256(data).hexdigest(),
        }
        if coord in jetbrains and jetbrains[coord] != entry["sha256"]:
            sys.exit(
                f"{coord}: sha256 {entry['sha256']} differs from verification-metadata.xml"
            )
        pins[coord] = entry
        print(f"{coord} {entry['sha1']}")
    pins_path.write_text(json.dumps(pins, indent=1, sort_keys=True) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "command", nargs="?", choices=["generate", "pin"], default="generate"
    )
    parser.add_argument(
        "--project-root", type=Path, default=Path("."), help="default: ."
    )
    parser.add_argument(
        "--kotlin-src", type=Path, default=Path("kotlin"), help="default: kotlin"
    )
    parser.add_argument(
        "--abi",
        choices=["class", "kosabi"],
        default="class",
        help="kosabi: source-only ABIs (Kosabi) for the modules that support them",
    )
    args = parser.parse_args()
    if args.command == "pin":
        pin(args.kotlin_src)
    else:
        generate(args.project_root, args.kotlin_src, args.abi)


if __name__ == "__main__":
    main()
