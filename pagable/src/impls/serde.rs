#[macro_export]
macro_rules! use_serde {
    ($ty:ty) => {
        impl pagable::PagableSerialize for $ty {
            fn pagable_serialize(
                &self,
                serializer: &mut dyn pagable::PagableSerializer,
            ) -> pagable::Result<()> {
                self.serialize(serializer.serde())
                    .with_context(|| format!("serializing type {}", std::any::type_name::<$ty>()))
            }
        }
        impl<'de> pagable::PagableDeserialize<'de> for $ty {
            fn pagable_deserialize<D: pagable::PagableDeserializer<'de> + ?Sized>(
                deserializer: &mut D,
            ) -> pagable::Result<Self> {
                <Self as pagable::__internal::serde::Deserialize<'de>>::deserialize(
                    deserializer.serde(),
                )
                .with_context(|| format!("deserializing type {}", std::any::type_name::<$ty>()))
            }
        }
    };
}

use_serde!(char);

// Written out rather than generated by `use_serde!` so a run of bytes moves
// as one slice instead of a dispatch per byte. The wire bytes are identical:
// postcard encodes `bytes` as a varint length plus the raw run, exactly what
// element-by-element writing after the same length produces.
impl PagableSerialize for u8 {
    fn pagable_serialize(&self, serializer: &mut dyn PagableSerializer) -> pagable::Result<()> {
        self.serialize(serializer.serde())
            .with_context(|| "serializing type u8")
    }

    fn pagable_serialize_vec(
        values: &[Self],
        serializer: &mut dyn PagableSerializer,
    ) -> pagable::Result<()> {
        serde::Serializer::serialize_bytes(serializer.serde(), values)
            .with_context(|| "serializing bytes")
    }
}

impl<'de> PagableDeserialize<'de> for u8 {
    fn pagable_deserialize<D: pagable::PagableDeserializer<'de> + ?Sized>(
        deserializer: &mut D,
    ) -> pagable::Result<Self> {
        <Self as serde::Deserialize<'de>>::deserialize(deserializer.serde())
            .with_context(|| "deserializing type u8")
    }

    fn pagable_deserialize_vec<D: pagable::PagableDeserializer<'de> + ?Sized>(
        deserializer: &mut D,
    ) -> pagable::Result<Vec<Self>> {
        let bytes = <&[u8] as serde::Deserialize<'de>>::deserialize(deserializer.serde())
            .with_context(|| "deserializing bytes")?;
        Ok(bytes.to_vec())
    }
}
