/// Return value of `type(any function)`.
pub const FUNCTION_TYPE: &str = "function";

#[derive(Debug, Allocative, Clone, Copy, Dupe, pagable::Pagable)]
#[doc(hidden)]
pub enum SpecialBuiltinFunction {
    List,
    Dict,
    Tuple,
    Set,
}

/// Type alias for functions generated by macro
#[doc(hidden)]
pub type NativeFuncFn = for<'v> fn(
    eval: &mut Evaluator<'v, '_, '_>,
    sig: &ParametersSpec<Value<'v>>,
    args: &Arguments<'v, '_>,
) -> crate::Result<Value<'v>>;

/// Storage for a `NativeFuncFn` and the parameters spec needed to call it
#[derive(Debug, ProvidesStaticType, Allocative, crate::StarlarkPagable)]
pub(crate) struct NativeFunc<'v>(
    #[allocative(skip)] // Not general enough
    #[starlark_pagable(skip = "{ |_a, _b, _c| { unimplemented!() } }")]
    pub(crate) NativeFuncFn,
    pub(crate) ParametersSpec<Value<'v>>,
);

impl<'v> NativeFunc<'v> {
    #[inline]
    pub(crate) fn invoke(
        &self,
        eval: &mut Evaluator<'v, '_, '_>,
        args: &Arguments<'v, '_>,
    ) -> crate::Result<Value<'v>> {
        (self.0)(eval, &self.1, args)
    }
}

/// Starlark representation of native (Rust) functions.
///
/// Almost always created with [`#[starlark_module]`](macro@crate::starlark_module). The
/// signature's default values are at the brand of the heap the function is allocated in.
#[derive(
    Derivative,
    ProvidesStaticType,
    Display,
    NoSerialize,
    Allocative,
    crate::StarlarkPagable
)]
#[derivative(Debug)]
#[display("{}", name)]
pub(crate) struct NativeFunction<'v> {
    #[derivative(Debug = "ignore")]
    pub(crate) function: NativeFunc<'v>,
    pub(crate) name: String,
    /// `.type` attribute and a type when this function is used in type expression.
    #[starlark_pagable(pagable)]
    pub(crate) as_type: Option<Ty>,
    #[starlark_pagable(pagable)]
    pub(crate) ty: Ty,
    /// Safe to evaluate speculatively.
    pub(crate) speculative_exec_safe: bool,
    #[derivative(Debug = "ignore")]
    #[starlark_pagable(pagable)]
    pub(crate) docs: DocItem,
    #[starlark_pagable(pagable)]
    pub(crate) special_builtin_function: Option<SpecialBuiltinFunction>,
}

/// Define the function type
#[starlark_value(type = FUNCTION_TYPE, frozen_vtable)]
impl<'v> StarlarkValue<'v> for NativeFunction<'v> {
    fn invoke(
        this: &Self,
        args: &Arguments<'v, '_>,
        eval: &mut Evaluator<'v, '_, '_>,
    ) -> crate::Result<Value<'v>> {
        this.function.invoke(eval, args)
    }

    fn get_attr(this: &Self, attribute: &str, heap: Heap<'v>) -> Option<Value<'v>> {
        if let Some(s) = this.as_type.as_ref().and_then(|t| t.as_name()) {
            if attribute == "type" {
                return Some(heap.alloc(s).to_value());
            }
        }
        None
    }

    fn eval_type(this: &Self) -> Option<Ty> {
        this.as_type.clone()
    }

    fn has_attr(_this: &Self, _attribute: &str, _heap: Heap<'v>) -> bool {
        // TODO(nga): implement properly.
        false
    }

    fn dir_attr(this: &Self) -> Vec<String> {
        if this.as_type.is_some() {
            vec!["type".to_owned()]
        } else {
            Vec::new()
        }
    }

    fn documentation(this: &Self) -> DocItem {
        this.docs.clone()
    }

    fn typechecker_ty(this: &Self) -> Option<Ty> {
        Some(this.ty.dupe())
    }

    fn at(this: &Self, index: Value<'v>, heap: Heap<'v>) -> crate::Result<Value<'v>> {
        match &this.special_builtin_function {
            Some(SpecialBuiltinFunction::List) => {
                let index = TypeCompiled::new(index, heap)?;
                Ok(TypeCompiled::type_list_of(index, heap).to_inner())
            }
            Some(SpecialBuiltinFunction::Set) => {
                let index = TypeCompiled::new(index, heap)?;
                Ok(TypeCompiled::type_set_of(index, heap).to_inner())
            }
            Some(SpecialBuiltinFunction::Tuple) => {
                // The 1-tuple type, whatever the element type is: a tuple of types is itself a
                // type (the tuple of those types), so it is not read as a list of elements here.
                let elem = TypeCompiled::new(index, heap)?;
                Ok(TypeCompiled::from_ty(&Ty::tuple(vec![elem.as_ty().clone()]), heap).to_inner())
            }
            _ => ValueError::unsupported(this, "[]"),
        }
    }

    fn at2(
        this: &Self,
        index0: Value<'v>,
        index1: Value<'v>,
        heap: Heap<'v>,
        _private: Private,
    ) -> crate::Result<Value<'v>> {
        match &this.special_builtin_function {
            Some(SpecialBuiltinFunction::Dict) => {
                let index0 = TypeCompiled::new(index0, heap)?;
                let index1 = TypeCompiled::new(index1, heap)?;
                Ok(TypeCompiled::type_dict_of(index0, index1, heap).to_inner())
            }
            Some(SpecialBuiltinFunction::Tuple) => {
                let item = TypeCompiled::new(index0, heap)?;
                if index1.downcast_ref::<Ellipsis>().is_some() {
                    Ok(TypeCompiled::from_ty(
                        &Ty::basic(TyBasic::Tuple(TyTuple::Of(ArcTy::new(
                            item.as_ty().clone(),
                        )))),
                        heap,
                    )
                    .to_inner())
                } else {
                    let second = TypeCompiled::new(index1, heap)?;
                    Ok(TypeCompiled::from_ty(
                        &Ty::tuple(vec![item.as_ty().clone(), second.as_ty().clone()]),
                        heap,
                    )
                    .to_inner())
                }
            }
            _ => ValueError::unsupported(this, "[,]"),
        }
    }
}

/// Type alias for functions generated by macro
#[doc(hidden)]
pub type NativeMethFn = for<'v> fn(
    eval: &mut Evaluator<'v, '_, '_>,
    this: Value<'v>,
    args: &Arguments<'v, '_>,
) -> crate::Result<Value<'v>>;

/// A method of a type, before it is bound to an instance.
///
/// It holds nothing that needs a heap or is built eagerly, so that it can be a `static`: the
/// function, the name, and a function that says what its parameters and result are, from which
/// its type and its documentation are computed when the typechecker or the docs ask.
#[derive(
    Derivative,
    Display,
    NoSerialize,
    ProvidesStaticType,
    Allocative,
    crate::StarlarkPagable
)]
#[derivative(Debug)]
#[display("{}", name)]
pub(crate) struct NativeMethod {
    #[derivative(Debug = "ignore")]
    #[allocative(skip)] // Not general enough
    #[starlark_pagable(skip = "{ |_a, _b, _c| { unimplemented!() } }")]
    pub(crate) function: NativeMethFn,
    #[starlark_pagable(skip = "\"\"")]
    pub(crate) name: &'static str,
    /// Safe to evaluate speculatively.
    pub(crate) speculative_exec_safe: bool,
    #[derivative(Debug = "ignore")]
    #[allocative(skip)]
    #[starlark_pagable(skip = "{ || { unimplemented!() } }")]
    components: fn() -> NativeCallableComponents,
    #[derivative(Debug = "ignore")]
    #[allocative(skip)]
    #[starlark_pagable(skip = "OnceLock::new()")]
    ty: OnceLock<Ty>,
}

impl NativeMethod {
    pub(crate) const fn new(
        name: &'static str,
        speculative_exec_safe: bool,
        components: fn() -> NativeCallableComponents,
        function: NativeMethFn,
    ) -> NativeMethod {
        NativeMethod {
            function,
            name,
            speculative_exec_safe,
            components,
            ty: OnceLock::new(),
        }
    }

    /// What the method's parameters and result are.
    pub(crate) fn components(&self) -> NativeCallableComponents {
        (self.components)()
    }

    /// The type of the method as a callable.
    pub(crate) fn ty(&self) -> &Ty {
        self.ty.get_or_init(|| self.components().make_type(None))
    }
}

#[starlark_value(type = "native_method")]
impl<'v> StarlarkValue<'v> for NativeMethod {
    fn documentation(this: &Self) -> DocItem {
        this.components().into_docs(None)
    }

    fn typechecker_ty(this: &Self) -> Option<Ty> {
        Some(this.ty().clone())
    }
}

/// Used by the `#[starlark(attribute)]` tag of [`#[starlark_module]`](macro@starlark_module)
/// to define a function that pretends to be an attribute.
///
/// Like [`NativeMethod`] it can be a `static`.
#[derive(
    Derivative,
    Display,
    NoSerialize,
    ProvidesStaticType,
    Allocative,
    crate::StarlarkPagable
)]
#[display("Attribute")]
#[derivative(Debug)]
pub(crate) struct NativeAttribute {
    /// Safe to evaluate speculatively.
    pub(crate) speculative_exec_safe: bool,
    #[starlark_pagable(skip = "None")]
    pub(crate) docstring: Option<&'static str>,
    #[derivative(Debug = "ignore")]
    #[allocative(skip)]
    #[starlark_pagable(skip = "{ || { unimplemented!() } }")]
    typ: fn() -> Ty,
    /// Essentially a `&dyn Fn(Value, Heap) -> Result<Value>`, but expanded out by hand, and
    /// with the `Self` hardcoded to always be `Option<Value>`
    ///
    /// We don't use a enum over whether the callable below requires a `data` argument as that
    /// would introduce an additional branch when calling the attribute
    #[starlark_pagable(skip = "None")]
    pub(crate) data: Option<Value<'static>>,
    #[allocative(skip)] // "Not general enough"
    #[starlark_pagable(skip = "{ |_a, _b, _c| { unimplemented!() } }")]
    pub(crate) callable:
        for<'v2> fn(Option<Value<'v2>>, Value<'v2>, Heap<'v2>) -> crate::Result<Value<'v2>>,
}

impl NativeAttribute {
    pub(crate) const fn new(
        speculative_exec_safe: bool,
        docstring: Option<&'static str>,
        typ: fn() -> Ty,
        data: Option<Value<'static>>,
        callable: for<'v2> fn(
            Option<Value<'v2>>,
            Value<'v2>,
            Heap<'v2>,
        ) -> crate::Result<Value<'v2>>,
    ) -> NativeAttribute {
        NativeAttribute {
            speculative_exec_safe,
            docstring,
            typ,
            data,
            callable,
        }
    }

    #[inline]
    pub(crate) fn invoke<'v>(&self, this: Value<'v>, heap: Heap<'v>) -> crate::Result<Value<'v>> {
        (self.callable)(HeapEdge::immortal().rebrand(self.data), this, heap)
    }

    /// The type the attribute evaluates to.
    pub(crate) fn ty(&self) -> Ty {
        (self.typ)()
    }
}

#[starlark_value(type = "attribute")]
impl<'v> StarlarkValue<'v> for NativeAttribute {
    fn documentation(this: &Self) -> DocItem {
        let ds = this
            .docstring
            .and_then(|ds| DocString::from_docstring(DocStringKind::Rust, ds));
        DocItem::Member(DocMember::Property(DocProperty {
            docs: ds,
            typ: this.ty(),
        }))
    }
}

/// A wrapper for a method with a self object already bound.
#[derive(
    Clone,
    Debug,
    Trace,
    Display,
    Freeze,
    NoSerialize,
    ProvidesStaticType,
    Allocative,
    crate::StarlarkPagable
)]
#[repr(C)]
#[display("{}", method)]
pub(crate) struct BoundMethod<'v> {
    pub(crate) method: FrozenValueTyped<'v, NativeMethod>,
    pub(crate) this: Value<'v>,
}

starlark_complex_value!(pub(crate) BoundMethod);

impl<'v> BoundMethod<'v> {
    /// Create a new [`BoundMethod`]. Given the expression `object.function`,
    /// the first argument would be `object`, and the second would be `getattr(object, "function")`.
    pub(crate) fn new(this: Value<'v>, method: FrozenValueTyped<'v, NativeMethod>) -> Self {
        BoundMethod { method, this }
    }
}

#[starlark_value(type = FUNCTION_TYPE)]
impl<'v> StarlarkValue<'v> for BoundMethod<'v> {
    fn invoke(
        this: &Self,
        args: &Arguments<'v, '_>,
        eval: &mut Evaluator<'v, '_, '_>,
    ) -> crate::Result<Value<'v>> {
        (this.method.function)(eval, this.this, args)
    }

    fn documentation(this: &Self) -> DocItem {
        this.method.to_value().documentation()
    }
}
