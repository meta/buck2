"""Generate BUCK files for Maven dependencies.

Reads Maven coordinates (`group:artifact:version`, one per line, `#` starts a comment), resolves
their compile and runtime dependencies from Maven repositories, and writes one `BUCK` file per
artifact: `remote_file` targets for the artifact and its sources, and a `prebuilt_jar` or
`android_prebuilt_aar` that depends on the artifact's own dependencies.

When two artifacts ask for different versions of a third, the highest version wins, as in Gradle.

Example, from `examples/android/demoapp`:

    python3 maven_to_buck.py app/libs/external_deps.txt --out app/libs --package //app/libs

Uses only the Python standard library.
"""

from __future__ import annotations

import argparse
import concurrent.futures
import functools
import hashlib
import logging
import os
import re
import sys
import urllib.error
import urllib.request
import xml.etree.ElementTree as ET
from collections.abc import Callable, Iterable
from dataclasses import dataclass, field
from pathlib import Path

logger: logging.Logger = logging.getLogger(__name__)

GOOGLE = "https://maven.google.com"
CENTRAL = "https://repo1.maven.org/maven2"
DEFAULT_REPOS = [GOOGLE, CENTRAL]
# With `--mirror`, artifacts of these groups get Google's Maven URL and the others Maven
# Central's: a mirror that merges both cannot say where an artifact came from.
GOOGLE_GROUP_PREFIXES = (
    "androidx.",
    "android.arch.",
    "com.android.",
    "com.google.android.",
    "com.google.firebase",
    "com.google.gms",
    "com.google.mlkit",
    "com.google.testing.platform",
)
HEADER = "# @generated by buck2/tools/maven_to_buck. Edit {deps} and run the tool again.\n"
HEADER_PREFIX = "# @generated by buck2/tools/maven_to_buck."
SKIPPED_SCOPES = {"test", "provided", "system", "import"}
NOT_FOUND = b"\0404"

GA = tuple[str, str]
Fetch = Callable[[str], "bytes | None"]


# Versions


_QUALIFIERS = {
    "alpha": 0,
    "a": 0,
    "beta": 1,
    "b": 1,
    "milestone": 2,
    "m": 2,
    "rc": 3,
    "cr": 3,
    "snapshot": 4,
    "": 5,
    "ga": 5,
    "final": 5,
    "release": 5,
    "sp": 6,
}
_RELEASE = (1, 5, "")


def _version_key(version: str) -> list[tuple[int, int, str]]:
    key: list[tuple[int, int, str]] = []
    numbers: list[int] = []  # the current run of numbers, whose trailing zeros do not count
    for part in re.findall(r"\d+|[a-z]+", version.lower()) + ["ga"]:
        if part.isdigit():
            numbers.append(int(part))
            continue
        while numbers and numbers[-1] == 0:
            numbers.pop()
        key += [(2, n, "") for n in numbers]
        numbers = []
        key.append((1, _QUALIFIERS[part], "") if part in _QUALIFIERS else (1, 7, part))
    while key and key[-1] == _RELEASE:
        key.pop()
    return key


def compare_versions(a: str, b: str) -> int:
    """Orders versions the way Maven does for the common cases: numbers numerically, then
    `alpha < beta < milestone < rc < snapshot < release < sp`, and `1.0 == 1.0.0`."""
    ka, kb = _version_key(a), _version_key(b)
    n = max(len(ka), len(kb))
    ka += [_RELEASE] * (n - len(ka))
    kb += [_RELEASE] * (n - len(kb))
    return (ka > kb) - (ka < kb)


def max_version(versions: Iterable[str]) -> str:
    return max(versions, key=functools.cmp_to_key(compare_versions))


def in_range(version: str, spec: str) -> bool:
    """Whether `version` is in a Maven range such as `[1.0,2.0)`."""
    lo, _, hi = (s.strip() for s in spec[1:-1].partition(","))
    if lo and compare_versions(version, lo) < (0 if spec[0] == "[" else 1):
        return False
    if hi and compare_versions(version, hi) > (0 if spec[-1] == "]" else -1):
        return False
    return True


# Repositories


def _path(group: str, artifact: str, version: str) -> str:
    return f"{group.replace('.', '/')}/{artifact}/{version}"


class Repos:
    """Fetches files from Maven repositories, in order, or through a mirror of them."""

    def __init__(self, repos: list[str], fetch: Fetch, mirror: str | None = None) -> None:
        self.repos: list[str] = [r.rstrip("/") for r in repos]
        self.mirror: str | None = mirror.rstrip("/") if mirror else None
        self._fetch = fetch
        self._repo_of: dict[tuple[str, str, str], str | None] = {}

    def get(self, group: str, artifact: str, version: str, name: str) -> bytes | None:
        """`<group path>/<artifact>/<version>/<name>` from the repository with the artifact's POM."""
        repo = self.repo_of(group, artifact, version)
        if repo is None:
            return None
        return self._fetch(f"{self.mirror or repo}/{_path(group, artifact, version)}/{name}")

    def versions(self, group: str, artifact: str) -> list[str]:
        """The versions `maven-metadata.xml` lists, in every repository."""
        found = []
        for base in [self.mirror] if self.mirror else self.repos:
            data = self._fetch(f"{base}/{group.replace('.', '/')}/{artifact}/maven-metadata.xml")
            if data:
                root = _strip_ns(ET.fromstring(data))
                found += [v.text.strip() for v in root.iter("version") if v.text]
        return found

    def repo_of(self, group: str, artifact: str, version: str) -> str | None:
        """The public repository named in this artifact's `mvn:` URLs."""
        k = (group, artifact, version)
        if k not in self._repo_of:
            self._repo_of[k] = self._find_repo(group, artifact, version)
        return self._repo_of[k]

    def _find_repo(self, group: str, artifact: str, version: str) -> str | None:
        pom = f"{_path(group, artifact, version)}/{artifact}-{version}.pom"
        if not self.mirror:
            return next((r for r in self.repos if self._fetch(f"{r}/{pom}") is not None), None)
        if self._fetch(f"{self.mirror}/{pom}") is None:
            return None
        if group.startswith(GOOGLE_GROUP_PREFIXES) and GOOGLE in self.repos:
            return GOOGLE
        return next((r for r in self.repos if r != GOOGLE), self.repos[0])


def http_fetcher(cache_dir: Path | None) -> Fetch:
    """Fetches URLs, None on 404, caching every answer (404s too) in `cache_dir`."""

    def fetch(url: str) -> bytes | None:
        cached = cache_dir / re.sub(r"[^A-Za-z0-9._-]", "_", url) if cache_dir else None
        if cached and cached.exists():
            data = cached.read_bytes()
            return None if data == NOT_FOUND else data
        request = urllib.request.Request(url, headers={"User-Agent": "buck2-maven-to-buck"})
        try:
            with urllib.request.urlopen(request, timeout=60) as response:
                data = response.read()
        except urllib.error.HTTPError as e:
            if e.code != 404:
                raise
            data = None
        if cached:
            cached.parent.mkdir(parents=True, exist_ok=True)
            cached.write_bytes(NOT_FOUND if data is None else data)
        return data

    return fetch


# POMs


@dataclass(frozen=True)
class Dependency:
    group: str
    artifact: str
    version: str  # a version, or a range such as `[1.0,2.0)`
    scope: str  # `compile` or `runtime`
    exclusions: frozenset[GA]


@dataclass
class Pom:
    group: str
    artifact: str
    version: str
    packaging: str
    dependencies: list[Dependency]
    # dependencyManagement: (group, artifact) -> {"version": ..., "scope": ...}
    managed: dict[GA, dict[str, str]]
    # This POM's own dependencyManagement versions. AndroidX publishes its Gradle constraints
    # there: for example `collection` 1.4.0 asks for `collection-ktx` 1.4.0, whose classes it
    # now contains, so that an older `collection-ktx` in the graph does not duplicate them.
    constraints: dict[GA, str]
    properties: dict[str, str]
    # The <dependency> elements, the parents' included, each with the properties of its POM.
    raw_dependencies: list[tuple[ET.Element, dict[str, str]]]


def _strip_ns(root: ET.Element) -> ET.Element:
    for e in root.iter():
        if isinstance(e.tag, str) and "}" in e.tag:
            e.tag = e.tag.split("}", 1)[1]
    return root


def _text(e: ET.Element | None, name: str) -> str | None:
    child = e.find(name) if e is not None else None
    return child.text.strip() if child is not None and child.text else None


def interpolate(value: str | None, props: dict[str, str]) -> str | None:
    """Replaces `${name}` with POM properties, recursively."""
    for _ in range(10):
        if value is None:
            return None
        new = re.sub(r"\$\{([^}]+)\}", lambda m: props.get(m.group(1), m.group(0)), value)
        if new == value:
            break
        value = new
    return value


class PomReader:
    """Reads effective POMs: parents merged, BOMs imported, properties interpolated."""

    def __init__(self, repos: Repos) -> None:
        self.repos = repos
        self._cache: dict[tuple[str, str, str], Pom | None] = {}

    def read(self, group: str, artifact: str, version: str) -> Pom | None:
        k = (group, artifact, version)
        if k not in self._cache:
            self._cache[k] = None  # breaks parent cycles
            data = self.repos.get(group, artifact, version, f"{artifact}-{version}.pom")
            if data is not None:
                self._cache[k] = self._parse(_strip_ns(ET.fromstring(data)), group, artifact, version)
        return self._cache[k]

    def _parse(self, root: ET.Element, group: str, artifact: str, version: str) -> Pom:
        parent_el = root.find("parent")
        parent = self._parent(parent_el)
        props = dict(parent.properties) if parent else {}
        if parent_el is not None:
            props["project.parent.groupId"] = _text(parent_el, "groupId") or ""
            props["project.parent.version"] = _text(parent_el, "version") or ""
        g = _text(root, "groupId") or _text(parent_el, "groupId") or group
        v = _text(root, "version") or _text(parent_el, "version") or version
        for prefix in ("project.", "pom."):
            props.update({prefix + "groupId": g, prefix + "artifactId": artifact, prefix + "version": v})
        props["version"] = v
        props.update({e.tag: (e.text or "").strip() for e in root.findall("properties/*") if isinstance(e.tag, str)})

        own, imported = self._managed(root, props)
        managed = (dict(parent.managed) if parent else {}) | imported | own
        constraints = {ga: m["version"] for ga, m in own.items() if m["version"]}
        raw = (parent.raw_dependencies if parent else []) + [(d, props) for d in root.findall("dependencies/dependency")]
        deps = [d for d in (_dependency(el, p, managed) for el, p in raw) if d is not None]
        return Pom(g, artifact, v, _text(root, "packaging") or "jar", deps, managed, constraints, props, raw)

    def _parent(self, parent_el: ET.Element | None) -> Pom | None:
        g, a, v = (_text(parent_el, n) for n in ("groupId", "artifactId", "version"))
        if not (g and a and v):
            return None
        return self.read(g, a, v)

    def _managed(self, root: ET.Element, props: dict[str, str]) -> tuple[dict[GA, dict[str, str]], dict[GA, dict[str, str]]]:
        """This POM's own dependencyManagement, and what its `import`-scope BOMs manage."""
        own: dict[GA, dict[str, str]] = {}
        imported: dict[GA, dict[str, str]] = {}
        for d in root.findall("dependencyManagement/dependencies/dependency"):
            g, a, v = (interpolate(_text(d, n), props) for n in ("groupId", "artifactId", "version"))
            scope = _text(d, "scope") or ""
            if not g or not a:
                continue
            if scope != "import":
                own[(g, a)] = {"version": v or "", "scope": scope}
                continue
            bom = self.read(g, a, v) if v else None
            for ga, m in (bom.managed if bom else {}).items():
                imported.setdefault(ga, m)
        return own, imported


def _dependency(d: ET.Element, props: dict[str, str], managed: dict[GA, dict[str, str]]) -> Dependency | None:
    """A compile or runtime dependency, or None for test, provided, optional and classifier ones."""
    group = interpolate(_text(d, "groupId"), props)
    artifact = interpolate(_text(d, "artifactId"), props)
    if not group or not artifact:
        return None
    m = managed.get((group, artifact), {})
    scope = _text(d, "scope") or m.get("scope") or "compile"
    if scope in SKIPPED_SCOPES or _text(d, "optional") == "true":
        return None
    if _text(d, "classifier") or (_text(d, "type") or "jar") not in ("jar", "aar", "bundle"):
        return None
    version = interpolate(_text(d, "version"), props) or m.get("version")
    if not version:
        return None
    exclusions = frozenset(
        (_text(x, "groupId") or "*", _text(x, "artifactId") or "*") for x in d.findall("exclusions/exclusion")
    )
    return Dependency(group, artifact, version, "runtime" if scope == "runtime" else "compile", exclusions)


# Resolution


@dataclass
class Resolved:
    group: str
    artifact: str
    version: str
    packaging: str
    compile_deps: list[GA] = field(default_factory=list)
    runtime_deps: list[GA] = field(default_factory=list)
    constraints: dict[GA, str] = field(default_factory=dict)


def _excluded(ga: GA, exclusions: frozenset[GA]) -> bool:
    return any(eg in ("*", ga[0]) and ea in ("*", ga[1]) for eg, ea in exclusions)


def pick_version(dep: Dependency, repos: Repos) -> str:
    """The version a dependency asks for; for a range, the highest published version in it."""
    v = dep.version
    if not v.startswith(("[", "(")):
        return v
    if "," not in v:
        return v.strip("[]()")
    matching = [x for x in repos.versions(dep.group, dep.artifact) if in_range(x, v)]
    if not matching:
        raise SystemExit(f"error: no version of {dep.group}:{dep.artifact} in {v}")
    return max_version(matching)


def _walk(roots: list[tuple[str, str, str]], selected: dict[GA, str], reader: PomReader):
    """One pass over the graph with the versions in `selected` (else the highest requested).
    Returns the graph and every version requested in it."""
    requested: dict[GA, set[str]] = {}
    for g, a, v in roots:
        requested.setdefault((g, a), set()).add(v)
    graph: dict[GA, Resolved] = {}
    seen: set[tuple[GA, frozenset[GA]]] = set()
    queue: list[tuple[GA, frozenset[GA]]] = [((g, a), frozenset()) for g, a, _ in roots]
    while queue:
        ga, exclusions = queue.pop()
        if (ga, exclusions) in seen:
            continue
        seen.add((ga, exclusions))
        version = selected.get(ga) or max_version(requested[ga])
        pom = reader.read(ga[0], ga[1], version)
        if pom is None:
            raise SystemExit(f"error: no POM for {ga[0]}:{ga[1]}:{version} in {' '.join(reader.repos.repos)}")
        node = graph.setdefault(ga, Resolved(ga[0], ga[1], version, pom.packaging, constraints=pom.constraints))
        for dep in pom.dependencies:
            dga = (dep.group, dep.artifact)
            if dga == ga or _excluded(dga, exclusions):
                continue
            requested.setdefault(dga, set()).add(pick_version(dep, reader.repos))
            if dga not in node.compile_deps + node.runtime_deps:
                (node.runtime_deps if dep.scope == "runtime" else node.compile_deps).append(dga)
            queue.append((dga, exclusions | dep.exclusions))
    for node in graph.values():
        for cga, v in node.constraints.items():
            if cga in graph:
                requested[cga].add(pick_version(Dependency(cga[0], cga[1], v, "compile", frozenset()), reader.repos))
    return graph, requested


def resolve(roots: list[tuple[str, str, str]], reader: PomReader) -> dict[GA, Resolved]:
    """Resolves the roots and their compile and runtime dependencies. The highest version
    requested anywhere in the graph wins, counting the constraints of the POMs in it (see
    `Pom.constraints`); passes repeat until the selection stops changing."""
    selected: dict[GA, str] = {}
    for _ in range(50):
        graph, requested = _walk(roots, selected, reader)
        new = {ga: max_version(vs) for ga, vs in requested.items() if ga in graph}
        if new == selected:
            return graph
        selected = new
    raise SystemExit("error: versions did not settle after 50 passes")


# BUCK files


def _sha1(repos: Repos, r: Resolved, name: str) -> str | None:
    data = repos.get(r.group, r.artifact, r.version, name + ".sha1")
    m = re.match(rb"\s*([0-9a-fA-F]{40})", data or b"")
    if m:
        return m.group(1).decode().lower()
    data = repos.get(r.group, r.artifact, r.version, name)
    return hashlib.sha1(data).hexdigest() if data is not None else None


def label(package: str, ga: GA) -> str:
    return f"{package}/{ga[0].replace('.', '/')}/{ga[1]}:{ga[1]}"


def _remote_file(name: str, out: str, sha1: str, url: str) -> str:
    return f'\nremote_file(\n    name = "{name}",\n    out = "{out}",\n    sha1 = "{sha1}",\n    url = "{url}",\n)\n'


def _deps_attr(attr: str, labels: list[str]) -> str:
    if not labels:
        return ""
    return f"    {attr} = [\n" + "".join(f'        "{x}",\n' for x in labels) + "    ],\n"


def render(r: Resolved, repos: Repos, package: str, deps_file: str) -> str:
    """The BUCK file of one resolved artifact."""
    labels = [label(package, ga) for ga in r.compile_deps + r.runtime_deps]
    head = HEADER.format(deps=deps_file)
    if r.packaging == "pom":
        return (
            head
            + "\n# A POM without an artifact: it only brings its dependencies.\n"
            + f'java_library(\n    name = "{r.artifact}",\n    visibility = ["PUBLIC"],\n'
            + _deps_attr("exported_deps", labels)
            + ")\n"
        )
    ext = "aar" if r.packaging == "aar" else "jar"
    repo = repos.repo_of(r.group, r.artifact, r.version)
    coords = f"mvn:{repo}:{r.group}:{r.artifact}"
    binary, sources = f"{r.artifact}-{r.version}.{ext}", f"{r.artifact}-{r.version}-sources.jar"
    sha1, sources_sha1 = _sha1(repos, r, binary), _sha1(repos, r, sources)
    if sha1 is None:
        raise SystemExit(f"error: no {binary} for {r.group}:{r.artifact}:{r.version}")
    text = head + _remote_file(f"{r.artifact}-remote", binary, sha1, f"{coords}:{ext}:{r.version}")
    if sources_sha1:
        text += _remote_file(f"{r.artifact}-sources-remote", sources, sources_sha1, f"{coords}:src:{r.version}")
    rule, attr = ("android_prebuilt_aar", "aar") if ext == "aar" else ("prebuilt_jar", "binary_jar")
    text += f'\n{rule}(\n    name = "{r.artifact}",\n    {attr} = ":{r.artifact}-remote",\n'
    if sources_sha1:
        text += f'    source_jar = ":{r.artifact}-sources-remote",\n'
    return text + '    visibility = ["PUBLIC"],\n' + _deps_attr("deps", labels) + ")\n"


def parse_deps_file(text: str) -> list[tuple[str, str, str]]:
    roots = []
    for n, line in enumerate(text.splitlines(), 1):
        parts = line.split("#", 1)[0].strip().split(":")
        if parts == [""]:
            continue
        if len(parts) == 4:  # group:artifact:packaging:version
            parts = [parts[0], parts[1], parts[3]]
        if len(parts) != 3 or not all(parts):
            raise SystemExit(f"error: line {n}: expected group:artifact:version, got `{line.strip()}`")
        roots.append((parts[0], parts[1], parts[2]))
    return roots


def write_buck_files(files: dict[GA, str], out: Path, prune: bool) -> tuple[int, int]:
    """Writes one BUCK file per artifact under `out`; returns (written, stale)."""
    written = set()
    for (g, a), text in sorted(files.items()):
        path = out / g.replace(".", "/") / a / "BUCK"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        written.add(path.resolve())
    stale = [p for p in out.rglob("BUCK") if p.resolve() not in written and p.read_text().startswith(HEADER_PREFIX)]
    if prune:
        for p in stale:
            p.unlink()
    return len(written), len(stale)


def _args(argv: list[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    parser.add_argument("deps_file", help="Maven coordinates, one `group:artifact:version` per line")
    parser.add_argument("--out", required=True, help="directory to write the BUCK files to")
    parser.add_argument("--package", required=True, help="Buck package of --out, for example //app/libs")
    parser.add_argument("--repo", action="append", help=f"repository, in lookup order, repeatable (default: {' '.join(DEFAULT_REPOS)})")
    parser.add_argument("--mirror", help="fetch every file from this mirror of the repositories instead")
    parser.add_argument(
        "--cache",
        default=os.path.join(os.path.expanduser("~"), ".cache", "buck2-maven-to-buck"),
        help="cache of downloaded POMs and checksums (default: %(default)s); empty disables it",
    )
    parser.add_argument("--prune", action="store_true", help="delete BUCK files this tool wrote earlier that are no longer needed")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    args = _args(argv)
    repos = Repos(args.repo or DEFAULT_REPOS, http_fetcher(Path(args.cache) if args.cache else None), args.mirror)
    graph = resolve(parse_deps_file(Path(args.deps_file).read_text()), PomReader(repos))
    package = args.package.rstrip("/")
    with concurrent.futures.ThreadPoolExecutor(16) as pool:
        texts = pool.map(lambda r: render(r, repos, package, args.deps_file), graph.values())
        files = dict(zip(graph, texts))
    written, stale = write_buck_files(files, Path(args.out), args.prune)
    logger.info("%d BUCK files written under %s", written, args.out)
    if stale:
        logger.info("%d BUCK files from an earlier run are no longer needed%s", stale, "; deleted" if args.prune else " (--prune deletes them)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
